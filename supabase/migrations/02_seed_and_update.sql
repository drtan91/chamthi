-- 6. CẬP NHẬT HÀM SUBMIT_VOTE ĐƠN GIẢN HÓA VÀ BẢO ĐẢM KHÓA CHẤM ĐIỂM
CREATE OR REPLACE FUNCTION public.submit_vote(
    p_team_id UUID,
    p_vocal_score INTEGER,
    p_performance_score INTEGER,
    p_participant_id UUID DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_is_locked BOOLEAN;
    v_part_id UUID;
    v_vote_id UUID;
BEGIN
    -- 1. Kiểm tra khóa hệ thống
    SELECT is_locked INTO v_is_locked FROM public.system_settings WHERE id = 1;
    IF v_is_locked = TRUE THEN
        RAISE EXCEPTION 'ERR_VOTING_LOCKED: Đã khóa chấm điểm' USING ERRCODE = 'P0001';
    END IF;

    -- 2. Xác định participant_id
    v_part_id := p_participant_id;
    IF v_part_id IS NULL THEN
        SELECT id INTO v_part_id FROM public.participants WHERE auth_user_id = auth.uid() LIMIT 1;
    END IF;

    IF v_part_id IS NULL THEN
        RAISE EXCEPTION 'ERR_UNAUTHORIZED: Không tìm thấy định danh nhân viên' USING ERRCODE = 'P0002';
    END IF;

    -- 3. Validate thang điểm 1-25
    IF p_vocal_score < 1 OR p_vocal_score > 25 OR p_performance_score < 1 OR p_performance_score > 25 THEN
        RAISE EXCEPTION 'ERR_INVALID_SCORE_RANGE: Điểm số phải từ 1 đến 25' USING ERRCODE = 'P0003';
    END IF;

    -- 4. UPSERT phiếu chấm điểm
    INSERT INTO public.votes (participant_id, team_id, vocal_score, performance_score, updated_at)
    VALUES (v_part_id, p_team_id, p_vocal_score, p_performance_score, NOW())
    ON CONFLICT (participant_id, team_id)
    DO UPDATE SET
        vocal_score = EXCLUDED.vocal_score,
        performance_score = EXCLUDED.performance_score,
        updated_at = NOW()
    RETURNING id INTO v_vote_id;

    RETURN jsonb_build_object('success', true, 'vote_id', v_vote_id);
END;
$$;

GRANT EXECUTE ON FUNCTION public.submit_vote(UUID, INTEGER, INTEGER, UUID) TO anon, authenticated;

